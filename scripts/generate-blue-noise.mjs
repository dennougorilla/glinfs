// Generate the 64x64 blue-noise threshold map used by the GIF encoder's
// "Blue noise" dithering, with Ulichney's void-and-cluster method
// (R. Ulichney, "The void-and-cluster method for dither array generation",
// SPIE 1913, 1993). Our own output, no third-party texture.
//
// Usage: node scripts/generate-blue-noise.mjs > src/features/export/encoders/blue-noise.js
// Deterministic: the same seed always gives the same file.

const SIZE = 64;
const N = SIZE * SIZE;
const SIGMA = 1.5;

let seed = 1;
const random = () => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed / 2147483648;
};

/** Toroidal Gaussian weights, indexed by (dy mod SIZE) * SIZE + (dx mod SIZE) */
const kernel = new Float64Array(N);
for (let dy = 0; dy < SIZE; dy++) {
  for (let dx = 0; dx < SIZE; dx++) {
    const ddx = Math.min(dx, SIZE - dx);
    const ddy = Math.min(dy, SIZE - dy);
    kernel[dy * SIZE + dx] = Math.exp(-(ddx * ddx + ddy * ddy) / (2 * SIGMA * SIGMA));
  }
}

/** Energy of every pixel from the set pixels of `bits` */
function energyOf(bits) {
  const energy = new Float64Array(N);
  for (let p = 0; p < N; p++) if (bits[p]) add(energy, p, 1);
  return energy;
}

/** Add `sign` times the kernel centred on p */
function add(energy, p, sign) {
  const px = p % SIZE;
  const py = (p / SIZE) | 0;
  for (let y = 0; y < SIZE; y++) {
    const ky = ((y - py + SIZE) % SIZE) * SIZE;
    for (let x = 0; x < SIZE; x++)
      energy[y * SIZE + x] += sign * kernel[ky + ((x - px + SIZE) % SIZE)];
  }
}

/** The set pixel with the most energy (tightest cluster) */
function tightest(bits, energy) {
  let best = -1;
  for (let p = 0; p < N; p++) if (bits[p] && (best < 0 || energy[p] > energy[best])) best = p;
  return best;
}

/** The unset pixel with the least energy (largest void) */
function largestVoid(bits, energy) {
  let best = -1;
  for (let p = 0; p < N; p++) if (!bits[p] && (best < 0 || energy[p] < energy[best])) best = p;
  return best;
}

// Initial pattern: 10 % random ones, relaxed until the tightest cluster
// would move into the largest void it leaves
const initial = new Uint8Array(N);
for (let placed = 0; placed < N / 10; ) {
  const p = Math.floor(random() * N);
  if (!initial[p]) {
    initial[p] = 1;
    placed++;
  }
}
{
  const energy = energyOf(initial);
  for (;;) {
    const cluster = tightest(initial, energy);
    initial[cluster] = 0;
    add(energy, cluster, -1);
    const hole = largestVoid(initial, energy);
    if (hole === cluster) {
      initial[cluster] = 1;
      add(energy, cluster, 1);
      break;
    }
    initial[hole] = 1;
    add(energy, hole, 1);
  }
}
const ones = initial.reduce((s, b) => s + b, 0);
const rank = new Int32Array(N).fill(-1);

// Phase 1: rank the initial ones, removing the tightest cluster each time
{
  const bits = initial.slice();
  const energy = energyOf(bits);
  for (let r = ones - 1; r >= 0; r--) {
    const p = tightest(bits, energy);
    bits[p] = 0;
    add(energy, p, -1);
    rank[p] = r;
  }
}
// Phases 2 and 3: add into the largest void until every pixel is ranked
// (past half, the largest void of the ones is the tightest cluster of the
// zeros; with energies kept from the ones the two are the same choice)
{
  const bits = initial.slice();
  const energy = energyOf(bits);
  for (let r = ones; r < N; r++) {
    const p = largestVoid(bits, energy);
    bits[p] = 1;
    add(energy, p, 1);
    rank[p] = r;
  }
}

// 256 levels, 16 pixels each
const levels = Uint8Array.from(rank, (r) => r >> 4);
const base64 = Buffer.from(levels).toString('base64');
const lines = base64.match(/.{1,96}/g) ?? [];

process.stdout.write(`/**
 * 64x64 blue-noise threshold map, values 0-255 (16 pixels each), for the
 * GIF encoder's "Blue noise" dithering. Generated by
 * scripts/generate-blue-noise.mjs (void-and-cluster, sigma ${SIGMA}); do not
 * edit by hand.
 * @module features/export/encoders/blue-noise
 */

const BASE64 =
${lines.map((l, i) => `  '${l}'${i < lines.length - 1 ? ' +' : ';'}`).join('\n')}

/** @returns {Uint8Array} ${N} values, row-major */
export function blueNoise64() {
  const text = atob(BASE64);
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) out[i] = text.charCodeAt(i);
  return out;
}
`);
